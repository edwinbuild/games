// Writes dist/sw.js after the build. The service worker pre-caches the home page and every solo
// any-time game (page, scripts, styles), so they work offline after the first visit; pages are
// fetched fresh when online (network first), hashed assets are cached for good, and anything
// else on the site is cached as it's used. The database and online rooms are never touched.
const fs = require('node:fs'), path = require('node:path'), { execSync } = require('node:child_process')
const root = path.resolve(__dirname, '..'), dist = path.join(root, 'dist')
const games = JSON.parse(execSync(`node -e "import('./src/games/registry.ts').then(m=>console.log(JSON.stringify(m.LISTED)))"`, { cwd: root }).toString())
const offline = games.filter((g) => !g.daily && !String(g.players ?? '').startsWith('online')).map((g) => g.slug)
const assets = fs.readdirSync(path.join(dist, 'assets'))
const urls = new Set(['/', '/manifest.webmanifest', '/favicon.svg', '/icons/icon-192.png'])
const addPage = (p, slug) => {
  const html = fs.readFileSync(path.join(dist, p, 'index.html'), 'utf8')
  urls.add(p ? `/${p}/` : '/')
  for (const m of html.matchAll(/(?:src|href)="(\/assets\/[^"]+)"/g)) urls.add(m[1])
  if (slug) for (const f of assets) if (f.startsWith(slug + '-') && /\.(js|css)$/.test(f)) urls.add('/assets/' + f)
}
addPage('', null)
for (const s of offline) addPage(s, s)
// Follow each script's static imports (shared chunks like the result ticket), but not lazy ones
// that only make sense online (rooms, boards).
for (let changed = true; changed;) {
  changed = false
  for (const u of [...urls]) {
    if (!u.endsWith('.js')) continue
    const code = fs.readFileSync(path.join(dist, u), 'utf8')
    for (const m of code.matchAll(/(?:from|import)\s*"\.\/([\w.-]+\.(?:js|css))"/g)) {
      const dep = '/assets/' + m[1]
      if (!urls.has(dep)) { urls.add(dep); changed = true }
    }
  }
}
const list = [...urls].sort()
const version = require('node:crypto').createHash('sha256').update(list.join('\n')).digest('hex').slice(0, 12)
const sw = `// Generated by scripts/sw.cjs. Do not edit.
const CACHE = 'pf-${version}'
const PRECACHE = ${JSON.stringify(list)}
const FONTS = /^https:\\/\\/fonts\\.(googleapis|gstatic)\\.com\\//

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
// Ignore Vary: module scripts send an Origin header the pre-cache requests didn't.
const match = (req, o = {}) => caches.match(req, { ignoreVary: true, ...o })
const put = (req, res) => { if (res && (res.ok || res.type === 'opaque')) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)) } return res }
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (FONTS.test(req.url)) {
    e.respondWith(match(req).then((hit) => hit || fetch(req).then((res) => put(req, res))))
    return
  }
  if (url.origin !== location.origin || url.pathname.startsWith('/stats')) return
  if (req.mode === 'navigate') {
    // Fresh when online; the cached page (ignoring ?room= and challenge links) when not.
    e.respondWith(fetch(req).then((res) => put(new Request(url.pathname), res)).catch(() =>
      match(url.pathname, { ignoreSearch: true }).then((hit) => hit || match('/'))))
    return
  }
  if (url.pathname.startsWith('/assets/')) {
    e.respondWith(match(req).then((hit) => hit || fetch(req).then((res) => put(req, res))))
    return
  }
  e.respondWith(match(req).then((hit) => { const net = fetch(req).then((res) => put(req, res)); return hit || net }))
})
`
fs.writeFileSync(path.join(dist, 'sw.js'), sw)
console.log(`sw.js: ${list.length} files pre-cached for ${offline.length} games (${offline.join(', ')})`)
